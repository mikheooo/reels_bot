"""Structured Reels Analyzer report generation.

This module restores the analyzer's user-facing report contract without exposing
API keys or coupling the report to the fact-check persistence models.
"""
import json

from app.worker.factcheck import call_gemini_api


REPORT_PROMPT = """Ты — Reels Analyzer Михаила. На основании сырого транскрипта и описания кадров
сделай аналитический разбор видео. Не выдумывай названия сервисов, API, цены,
архитектуру или визуальные детали, которых нет в исходном материале. Если данных
недостаточно, явно напиши «не подтверждено по видео» или «не применимо».

Верни ответ строго в этой структуре, без вступления:

**КРАТКО ДЛЯ КАНАЛА:**
1–2 предложения о том, о чём видео и в чём его практическая механика.

---

### 1. О ЧЁМ ВИДЕО
* **Содержание:** что показано или сказано.
* **Проблема / Возможность:** какую задачу это решает.

---

### 2. МЕХАНИКА (как это работает)
Пошагово опиши механику процесса только по доказанным данным. Если полный
Data Flow не показан, укажи, что он восстановлен неполно или не применим.

---

### 3. КЛЮЧЕВЫЕ КОМПОНЕНТЫ
* **Платформы и инструменты:** только упомянутые или явно показанные.
* **API и форматы:** только если они подтверждены видео.
* Для каждого компонента укажи: 📺 [В ВИДЕО], 🧠 [КОНТЕКСТ ИИ] или ⚠️ [ПРЕДПОЛОЖЕНИЕ].

---

### 4. ФАКТ VS ВЫМЫСЕЛ
* **📺 [В ВИДЕО]:** что непосредственно видно или сказано.
* **🧠 [КОНТЕКСТ ИИ]:** внешнее знание или логический вывод.
* **⚠️ [ПРЕДПОЛОЖЕНИЕ]:** что нельзя подтвердить по ролику.
* Отдельно укажи маркетинговые обещания и скрытые ограничения, если они есть.

---

### 🚀 МОЖНО ЛУЧШЕ
Заполняй только при объективно более простом, дешёвом или надёжном варианте.
Иначе напиши: «не требуется».

---

### 5. РЕАЛИСТИЧНОСТЬ И СЛОЖНОСТЬ
Оцени от 1 до 10 и дай по одному короткому обоснованию:
* **Техническая сборка / реализация:** X/10 — ...
* **Легализация доступа к API:** X/10 — ...
* **Риски серого пути / блокировок:** X/10 — ...
Если слой не применим, напиши «не применимо» и почему.

---

### 6. ЗАДАЧА ДЛЯ МИХАИЛА
Сформулируй конкретную практическую задачу строго в рамках видео.
* **Инженерная суть:** ...
* **Применимость:** ...
* **Монетизация / эффект:** только качественный эффект, без придуманных сумм.

#### КРИТЕРИИ ГОТОВНОСТИ:
3–4 измеримых критерия только для инструментов и шагов, реально присутствующих
в видео. Не добавляй сторонние платформы и интеграции.

ИСХОДНЫЕ ДАННЫЕ ВИДЕО:
{transcript}
"""


async def generate_structured_analysis(transcript: str) -> str:
    """Generate the restored markdown report using the configured Gemini router."""
    payload = {
        "contents": [{"role": "user", "parts": [{"text": REPORT_PROMPT.format(transcript=transcript)}]}],
        "generationConfig": {"temperature": 0.2},
    }
    response = await call_gemini_api(payload)
    text = response["candidates"][0]["content"]["parts"][0]["text"]
    return text.strip()
