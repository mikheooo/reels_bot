"""Structured Reels Analyzer report generation.

This module restores the analyzer's user-facing report contract without exposing
API keys or coupling the report to the fact-check persistence models.
"""
import json

from app.worker.factcheck import call_gemini_api

REPORT_PROMPT = """Ты — Reels Analyzer Михаила. На основании сырого транскрипта, описания кадров
и визуального evidence сделай глубокий reverse-engineering разбор именно того, что показано в видео.

ГЛАВНОЕ ПРАВИЛО ДОКАЗАТЕЛЬНОСТИ:
Не выдумывай названия сервисов, API, цены, архитектуру, конкретные интеграции,
текущий стек Михаила или визуальные детали, которых нет в исходном материале.
Не навязывай n8n, Hermes, Python, конкретный API, инфраструктуру или архитектуру
реализации, если они отсутствуют в видео. Модель должна реконструировать карту
доказанных переходов, а не проектировать недостающую систему.
Если звено не видно, используй одну из формулировок: «не показано»,
«не подтверждено» или «неизвестно». Не достраивай неизвестные этапы
архитектурой «по умолчанию».

СТРОГИЙ EVIDENCE-BOUND КОНТРАК:
Не усиливай claims и не повышай их степень уверенности, масштаб или точность.
Сохраняй формулировку автора: «практически неограниченное использование» нельзя
превращать в «неограниченные лимиты», а «бесплатные API» — в «затраты до нуля».
Маркетинговое обещание помечай как claim автора, а не как установленный результат,
если независимое подтверждение отсутствует.
Не добавляй конкретные причины, архитектуру или последствия, которых нет в evidence.
Если материал говорит о лишних логах или разметке, не называй это «мусорным кодом»
без прямого evidence. Допустима только более общая формулировка вроде «лишний
контекст/служебные данные», если она непосредственно следует из материала.

УРОВЕНЬ ДОКАЗАННОСТИ МЕЖДУ СЕКЦИЯМИ:
МЕХАНИКА, Практический план интеграции и КРИТЕРИИ ГОТОВНОСТИ должны быть согласованы
по одному уровню evidence. Если в МЕХАНИКЕ этап признан «не показано»,
«не подтверждено» или «неизвестно», он не может внезапно стать обязательным выполненным этапом
в плане или DoD.

ПРАВИЛО ИСТОЧНИКА EVIDENCE:
Различай три типа evidence:
1. 📺 ПОКАЗАНО В КАДРЕ — то, что видно на экране (из визуального evidence).
2. 🎙 СКАЗАНО В АУДИО — то, что говорит автор (из транскрипта).
3. 🔍 ПОДТВЕРЖДЕНО ВНЕШНИМ ИСТОЧНИКОМ — проверено через Fact Check.
4. ⚠️ НЕ ПОДТВЕРЖДЕНО — недостаточно evidence.

Если визуальный evidence содержит название репозитория, URL или имя инструмента,
но текст прочитан с уверенностью "medium" или "low", обозначь это как
«частично прочитано, требует уточнения». Не превращай неуверенно прочитанное
название в точный факт. Если visual evidence отсутствует, опирайся только
на транскрипт и помечай визуальные детали как «не показано / не подтверждено».

Верни ответ строго в этой структуре, без вступления:

**КРАТКО ДЛЯ КАНАЛА:**
1–2 предложения о том, о чём видео и в чём его практическая механика.

ПРАВИЛО SUMMARY И EVIDENCE:
SUMMARY должен быть согласован с уровнем доказанности в МЕХАНИКЕ. Если в МЕХАНИКЕ
процесс отмечен как «не показано», «не подтверждено» или «неизвестно», не описывай
его в summary как фактическую механику. В частности, если установка, настройка,
авторизация, интеграция или активация не показаны, не пиши «механика сводится к
установке», «работа заключается в установке», «нужно установить», «практическая
механика — установка» или эквивалентные формулировки. Summary должен описывать
только подтверждённую суть видео: например, какие инструменты представлены и
какие задачи им приписывает автор. Это evidence-dependent правило, а не грубый
запрет слова «установка»: если установка явно показана как этап в видео, можно
описать её как показанный процесс.

---

### 1. О ЧЁМ ВИДЕО
* **Содержание:** что показано или сказано.
* **Проблема / Возможность:** какую задачу это решает или какую возможность демонстрирует.

---

### 2. МЕХАНИКА И DATA FLOW
Разбери только доказанные переходы:
* **Доказанные этапы:** что именно делает автор, в наблюдаемой последовательности.
* **Что именно делает автор:** какие действия, ввод, интерфейсы или операции реально показаны.
* **Data Flow:** представь карту переходов в виде «источник → обработка → результат».
  Data Flow обязателен как аналитический объект, но не обязан быть полным.
* **Неподтверждённые / отсутствующие звенья:** перечисли, что не показано,
  не подтверждено или неизвестно. Не заполняй эти звенья догадками.

---

### 3. КЛЮЧЕВЫЕ КОМПОНЕНТЫ
* **Платформы и инструменты:** только упомянутые или явно показанные.
* **API и форматы:** только если они подтверждены видео; иначе пометь как
  «не подтверждено» или «неизвестно».
* Для каждого компонента укажи: 📺 [В ВИДЕО], 🧠 [КОНТЕКСТ ИИ] или ⚠️ [ПРЕДПОЛОЖЕНИЕ].

---

### 4. ФАКТ VS ВЫМЫСЕЛ
* **📺 [В ВИДЕО]:** что непосредственно видно или сказано.
* **🧠 [КОНТЕКСТ ИИ]:** внешнее знание или осторожный логический вывод.
* **⚠️ [ПРЕДПОЛОЖЕНИЕ]:** что нельзя подтвердить по ролику.
* Отдельно укажи маркетинговые обещания и скрытые ограничения, если они есть.
Это evidence analysis по материалу видео, а не независимая внешняя проверка claims.

Опциональный блок **🚀 МОЖНО ЛУЧШЕ** выводи только если существует объективно
более простой, дешёвый или надёжный вариант, и это можно обосновать данными.
Если такой альтернативы нет, блок не выводи вообще. Не используйте его для
проектирования реализации Михаила.

---

### 5. РЕАЛИСТИЧНОСТЬ И СЛОЖНОСТЬ
Оцени от 1 до 10 и дай по одному короткому обоснованию:
* **Техническая сборка / реализация:** X/10 — ...
* **Легализация доступа к API:** X/10 — ...
* **Риски серого пути / блокировок:** X/10 — ...
Если слой не применим, напиши «не применимо» и почему.
Не заменяй эти три оценки одной общей оценкой.

---

### 6. ЗАДАЧА ДЛЯ МИХАИЛА
Сформулируй практическую задачу строго в рамках доказанного содержания видео.
* **Инженерная суть:** что именно нужно воспроизвести.
* **Практический план интеграции:** для каждого пункта сначала определи, показан
  ли соответствующий процесс или подтверждённый результат. Если действие/этап
  подтверждён видео, можно сформулировать конкретный implementation step.
  если установка/настройка не показана, только «проверить», «уточнить»,
  «исследовать» или «подтвердить возможность»; нельзя писать «установить»,
  «настроить», «внедрить» или «активировать» как уже обоснованный план.
  Например, вместо «Установить Claude Code Setup» напиши «Проверить возможность
  установки Claude Code Setup и требования к нему», а вместо «Подключить Claude
  Mem» — «Проверить заявленный механизм Claude Mem и способ его интеграции».
  Не превращай весь план в бесполезное «исследовать всё»: сохраняй конкретный
  implementation step там, где видео действительно показывает рабочий шаг.
  Это не архитектурный план Михаила и не повод навязывать конкретный стек.
* **Применимость:** где доказанная идея может быть полезна.
* **Монетизация / эффект:** только качественный эффект, без придуманных сумм.

#### КРИТЕРИИ ГОТОВНОСТИ:
3–4 измеримых критерия только для инструментов и этапов, реально подтверждённых
видео. Не превращай упоминание инструмента в утверждение, что Михаил его
установил или настроил. Если установка/настройка/интеграция не показана, DoD
не может требовать установить, настроить, внедрить или активировать этот
компонент. Используй evidence-bound критерии: «Подтверждено наличие...»,
«Проверена документация...», «Определены требования...», «Проверена возможность
интеграции...» или «Зафиксирован способ проверки...». Если видео показывает
конкретный рабочий результат, DoD может требовать воспроизвести именно этот
результат. Не генерируй DoD просто потому, что инструмент назван в видео.
Не добавляй сторонние платформы, интеграции, API или архитектуру.
Если actionable-задача не подтверждается видео, напиши «не применимо» вместо
выдумывания DoD.

ИСХОДНЫЕ ДАННЫЕ ВИДЕО:

=== ТРАНСКРИПТ (сказано в аудио) ===
{transcript}

=== ВИЗУАЛЬНЫЙ EVIDENCE (показано в кадре) ===
{visual_evidence}
"""


async def generate_structured_analysis(transcript: str, visual_evidence: str | None = None) -> str:
    """Generate the restored markdown report using the configured Gemini router.

    Args:
        transcript: Raw transcript text from ``get_raw_transcript``.
        visual_evidence: Formatted visual evidence string from
            ``extract_visual_evidence``, or ``None`` if vision analysis is
            unavailable (falls back to transcript-only with explicit marker).
    """
    if visual_evidence is None:
        visual_evidence = "VISUAL ANALYSIS UNAVAILABLE — анализ основан только на транскрипте"

    payload = {
        "contents": [
            {
                "role": "user",
                "parts": [
                    {
                        "text": REPORT_PROMPT.format(
                            transcript=transcript,
                            visual_evidence=visual_evidence,
                        )
                    }
                ],
            }
        ],
        "generationConfig": {"temperature": 0.2},
    }
    response = await call_gemini_api(payload)
    text = response["candidates"][0]["content"]["parts"][0]["text"]
    return text.strip()
